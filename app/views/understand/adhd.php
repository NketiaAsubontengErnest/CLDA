                    <h2 class="h3 text-primary mb-4">Possible Causes of ADHD</h2>
                    <p>There’s been a lot of research in the last few years that has pointed to possible causes of ADHD. Brain-imaging studies have looked at brain anatomy and wiring in people who have ADHD and those who don’t.</p>
                    <p>Studies have shown that brain development is very similar. But kids with ADHD have a delay in development of about three years in some specific parts of the brain. These are the areas involved in executive functions. That’s why kids with ADHD may act one to three years younger than other kids their age.</p>
                    <p>Research also shows some differences in the networks that help parts of the brain communicate with each other. And there are differences in how brain chemicals act when they’re involved in that communication.</p>
                    <p>Genetics also appear to play a role. Research has shown that ADHD tends to run in families. A child with ADHD has a one in four chance of having at least one parent who also has it. And there’s a strong likelihood that another close family member also has ADHD. It’s important to know that these differences have nothing to do with intelligence or IQ. Kids with ADHD are just as smart as kids without ADHD.</p>
