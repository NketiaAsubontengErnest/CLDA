                <div class="p-4 p-md-5 bg-white shadow-sm rounded-4">
                    <p class="mb-4">Visual processing issues are complex and often go undetected on standard vision tests. Scientists have identified eight different types:</p>
                    <div class="row g-4">
                        <div class="col-md-6">
                            <div class="p-3 bg-light rounded-4 h-100">
                                <h6 class="fw-bold text-primary">Visual discrimination issues</h6>
                                <p class="small mb-0">Difficulty seeing the difference between two similar letters, shapes or objects. May confuse d and b, or p and q.</p>
                            </div>
                        </div>
                        <div class="col-md-6">
                            <div class="p-3 bg-light rounded-4 h-100">
                                <h6 class="fw-bold text-primary">Visual figure-ground discrimination issues</h6>
                                <p class="small mb-0">Trouble pulling a shape or character from its background. Hard to find specific information on a page.</p>
                            </div>
                        </div>
                        <div class="col-md-6">
                            <div class="p-3 bg-light rounded-4 h-100">
                                <h6 class="fw-bold text-primary">Visual sequencing issues</h6>
                                <p class="small mb-0">Difficulty telling the order of symbols, words or images. May struggle to write answers separately, skip lines, or reverse/misread letters.</p>
                            </div>
                        </div>
                        <div class="col-md-6">
                            <div class="p-3 bg-light rounded-4 h-100">
                                <h6 class="fw-bold text-primary">Visual-motor processing issues</h6>
                                <p class="small mb-0">Difficulty using visual feedback to coordinate body movement. Writing within lines, copying from a book, and not bumping into things can be tough.</p>
                            </div>
                        </div>
                        <div class="col-md-6">
                            <div class="p-3 bg-light rounded-4 h-100">
                                <h6 class="fw-bold text-primary">Long- or short-term visual memory issues</h6>
                                <p class="small mb-0">Difficulty recalling what was seen. Struggles with reading, spelling, remembering what was read, and using a calculator/keyboard.</p>
                            </div>
                        </div>
                        <div class="col-md-6">
                            <div class="p-3 bg-light rounded-4 h-100">
                                <h6 class="fw-bold text-primary">Visual-spatial issues</h6>
                                <p class="small mb-0">Difficulty telling where objects are in space (distance, paper descriptions, maps). May struggle with judging time.</p>
                            </div>
                        </div>
                        <div class="col-md-6">
                            <div class="p-3 bg-light rounded-4 h-100">
                                <h6 class="fw-bold text-primary">Visual closure issues</h6>
                                <p class="small mb-0">Difficulty identifying an object when only parts are visible. Hard to recognize words if a letter is missing, affecting spelling.</p>
                            </div>
                        </div>
                        <div class="col-md-6">
                            <div class="p-3 bg-light rounded-4 h-100">
                                <h6 class="fw-bold text-primary">Letter and symbol reversal issues</h6>
                                <p class="small mb-0">Switching letters or numbers when writing. Substituting letters when reading (after age 7). Trouble with letter formation affecting reading, writing, and math.</p>
