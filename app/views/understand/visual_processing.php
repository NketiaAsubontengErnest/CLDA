                    <p class="small mb-4">When your child starts struggling in school and it seems like it’s a vision problem, the first step is a trip to the pediatrician. Before you go it’s important to take notes on what you’ve been seeing in your child. The doctor will most likely give your child a vision test and look for any health issues with his eyes. If everything checks out the doctor may refer you to a specialist for further evaluation.</p>
