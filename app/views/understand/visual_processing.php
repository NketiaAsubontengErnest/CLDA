                            <span class="text-muted">Your child’s doctor may refer you to a pediatric ophthalmologist, a medical doctor who treats eye and vision problems in children. This specialist will likely perform a complete examination of your child’s eyes and vision to look for physical reasons for your child’s issues. If there are none there will be no further vision testing.</span>
