                            <span class="text-muted">Instead of sending you to a pediatric ophthalmologist your child’s doctor may refer you to a pediatric optometrist. This is a health-care professional who provides primary eye care to children. In addition to prescribing glasses, optometrists can also evaluate patients for vision or eye problems.</span>
                        </li>
                        <li class="mb-3">
                            <strong class="d-block text-dark">Neuropsychologist:</strong>
                            <span class="text-muted">If everything checks out with your child’s vision and eye health, the eye specialists or your child’s doctor may refer you to a neuropsychologist. This is a psychologist who is trained to diagnose learning issues and weakness. The neuropsychologist may perform a series of tests to see how your child’s visual issues are affecting her development. The tests are designed to measure intelligence, academic skills, language skills, memory and attention abilities. The specialist also may interview you and your child’s teachers for more information. This is the specialist who can tell you if your child has visual perception issues.</span>
